"""Versioned schema migrations for SQLite and Postgres.

Migration 1 reproduces the original schema exactly (with `IF NOT EXISTS`), so a
database created by the old `init_db.py` upgrades in place. Every later change is
an additive, idempotent step recorded in `schema_migrations`.

On Postgres all pending migrations run in one transaction behind an advisory lock,
so concurrent serverless cold starts can't race each other.
"""

from __future__ import annotations

import logging
from collections.abc import Callable

from werkzeug.security import generate_password_hash

from .db import POSTGRES, Database
from .security import is_password_hash

log = logging.getLogger(__name__)

_LOCK_ID = 727_274_001  # arbitrary constant shared by all app instances

DEFAULT_CATEGORIES = [
    ('Food', 'expense'),
    ('Groceries', 'expense'),
    ('Transport', 'expense'),
    ('Bills', 'expense'),
    ('Shopping', 'expense'),
    ('Entertainment', 'expense'),
    ('Health', 'expense'),
    ('Education', 'expense'),
    ('Rent', 'expense'),
    ('Others', 'expense'),
    ('Salary', 'income'),
    ('Freelance', 'income'),
    ('Business', 'income'),
    ('Investment', 'income'),
    ('Gift', 'income'),
    ('Other Income', 'income'),
]

_BASELINE_SQLITE = [
    '''CREATE TABLE IF NOT EXISTS users (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        username TEXT NOT NULL UNIQUE,
        email TEXT NOT NULL UNIQUE,
        password TEXT NOT NULL
    )''',
    '''CREATE TABLE IF NOT EXISTS categories (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        user_id INTEGER,
        name TEXT NOT NULL,
        type TEXT NOT NULL,
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
    )''',
    '''CREATE TABLE IF NOT EXISTS transactions (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        user_id INTEGER NOT NULL,
        category TEXT NOT NULL,
        amount NUMERIC NOT NULL,
        type TEXT NOT NULL,
        date TEXT NOT NULL,
        description TEXT,
        title TEXT,
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
    )''',
    '''CREATE TABLE IF NOT EXISTS budgets (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        user_id INTEGER NOT NULL,
        category_id INTEGER NOT NULL,
        amount NUMERIC NOT NULL,
        month INTEGER NOT NULL,
        year INTEGER NOT NULL,
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
        FOREIGN KEY (category_id) REFERENCES categories(id) ON DELETE CASCADE
    )''',
    'CREATE INDEX IF NOT EXISTS idx_transactions_user_date ON transactions(user_id, date)',
    'CREATE INDEX IF NOT EXISTS idx_transactions_user_type ON transactions(user_id, type)',
    'CREATE INDEX IF NOT EXISTS idx_budgets_user_month_year ON budgets(user_id, month, year)',
]

# Fresh Postgres databases also get CHECK constraints as a second line of defence
# behind application-level validation.
_BASELINE_POSTGRES = [
    '''CREATE TABLE IF NOT EXISTS users (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        username TEXT NOT NULL UNIQUE,
        email TEXT NOT NULL UNIQUE,
        password TEXT NOT NULL
    )''',
    '''CREATE TABLE IF NOT EXISTS categories (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
        name TEXT NOT NULL,
        type TEXT NOT NULL CHECK (type IN ('income', 'expense'))
    )''',
    r'''CREATE TABLE IF NOT EXISTS transactions (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        category TEXT NOT NULL,
        amount NUMERIC(14, 2) NOT NULL CHECK (amount > 0),
        type TEXT NOT NULL CHECK (type IN ('income', 'expense')),
        date TEXT NOT NULL CHECK (date ~ '^\d{4}-\d{2}-\d{2}$'),
        description TEXT,
        title TEXT
    )''',
    '''CREATE TABLE IF NOT EXISTS budgets (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        category_id BIGINT NOT NULL REFERENCES categories(id) ON DELETE CASCADE,
        amount NUMERIC(14, 2) NOT NULL CHECK (amount > 0),
        month INTEGER NOT NULL CHECK (month BETWEEN 1 AND 12),
        year INTEGER NOT NULL
    )''',
    'CREATE INDEX IF NOT EXISTS idx_transactions_user_date ON transactions(user_id, date)',
    'CREATE INDEX IF NOT EXISTS idx_transactions_user_type ON transactions(user_id, type)',
    'CREATE INDEX IF NOT EXISTS idx_budgets_user_month_year ON budgets(user_id, month, year)',
]


def _baseline(db: Database) -> None:
    db.script(_BASELINE_POSTGRES if db.dialect == POSTGRES else _BASELINE_SQLITE)


def _plain_category_names(db: Database) -> None:
    """Older builds stored default categories with emoji suffixes; normalize them."""
    for name, type_ in DEFAULT_CATEGORIES:
        for suffix in (' 🍔', ' 🛒', ' 🚕', ' 💡', ' 🛍️', ' 🎬', ' 🏥', ' 📚', ' 🏠', ' ?', '?', ' �', '�'):
            legacy = name + suffix
            db.execute('UPDATE categories SET name = ? WHERE type = ? AND name = ?', (name, type_, legacy))
            db.execute('UPDATE transactions SET category = ? WHERE type = ? AND category = ?', (name, type_, legacy))


def _seed_default_categories(db: Database) -> None:
    for name, type_ in DEFAULT_CATEGORIES:
        exists = db.one('SELECT id FROM categories WHERE user_id IS NULL AND name = ? AND type = ?', (name, type_))
        if not exists:
            db.execute('INSERT INTO categories (user_id, name, type) VALUES (NULL, ?, ?)', (name, type_))


def _unique_budgets_and_indexes(db: Database) -> None:
    # Keep the newest row for any duplicated (user, category, month, year) budget.
    db.execute(
        '''DELETE FROM budgets WHERE id NOT IN (
               SELECT keep_id FROM (
                   SELECT MAX(id) AS keep_id FROM budgets GROUP BY user_id, category_id, month, year
               ) AS keepers
           )'''
    )
    db.script(
        [
            'CREATE UNIQUE INDEX IF NOT EXISTS ux_budgets_user_category_period ON budgets(user_id, category_id, month, year)',
            'CREATE INDEX IF NOT EXISTS idx_categories_user ON categories(user_id)',
            'CREATE INDEX IF NOT EXISTS idx_transactions_user_category ON transactions(user_id, category)',
        ]
    )


def _add_column(db: Database, table: str, column: str, ddl: str) -> None:
    if column not in db.column_names(table):
        db.script([f'ALTER TABLE {table} ADD COLUMN {column} {ddl}'])


def _account_metadata(db: Database) -> None:
    _add_column(db, 'users', 'created_at', 'TEXT')
    _add_column(db, 'users', 'is_demo', 'INTEGER NOT NULL DEFAULT 0')
    _add_column(db, 'transactions', 'created_at', 'TEXT')


def _rate_limits_and_ai_cache(db: Database) -> None:
    if db.dialect == POSTGRES:
        db.script(
            [
                '''CREATE TABLE IF NOT EXISTS rate_events (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    bucket TEXT NOT NULL,
                    key TEXT NOT NULL,
                    created_at BIGINT NOT NULL
                )''',
                '''CREATE TABLE IF NOT EXISTS ai_cache (
                    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                    kind TEXT NOT NULL,
                    fingerprint TEXT NOT NULL,
                    payload TEXT NOT NULL,
                    created_at BIGINT NOT NULL,
                    PRIMARY KEY (user_id, kind)
                )''',
            ]
        )
    else:
        db.script(
            [
                '''CREATE TABLE IF NOT EXISTS rate_events (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    bucket TEXT NOT NULL,
                    key TEXT NOT NULL,
                    created_at INTEGER NOT NULL
                )''',
                '''CREATE TABLE IF NOT EXISTS ai_cache (
                    user_id INTEGER NOT NULL,
                    kind TEXT NOT NULL,
                    fingerprint TEXT NOT NULL,
                    payload TEXT NOT NULL,
                    created_at INTEGER NOT NULL,
                    PRIMARY KEY (user_id, kind),
                    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
                )''',
            ]
        )
    db.script(['CREATE INDEX IF NOT EXISTS idx_rate_events_lookup ON rate_events(bucket, key, created_at)'])


def _hash_plaintext_passwords(db: Database) -> None:
    """Replace any legacy plaintext password with a salted scrypt hash."""
    rows = db.all('SELECT id, password FROM users')
    upgraded = 0
    for row in rows:
        stored = row['password'] or ''
        if not is_password_hash(stored):
            db.execute('UPDATE users SET password = ? WHERE id = ?', (generate_password_hash(stored), row['id']))
            upgraded += 1
    if upgraded:
        log.warning('Hashed %d legacy plaintext password(s).', upgraded)


MIGRATIONS: list[tuple[int, str, Callable[[Database], None]]] = [
    (1, 'baseline schema', _baseline),
    (2, 'plain default category names', _plain_category_names),
    (3, 'seed default categories', _seed_default_categories),
    (4, 'unique budgets and lookup indexes', _unique_budgets_and_indexes),
    (5, 'account and transaction metadata', _account_metadata),
    (6, 'rate limiting and AI cache tables', _rate_limits_and_ai_cache),
    (7, 'hash legacy plaintext passwords', _hash_plaintext_passwords),
]


def migrate(db: Database) -> list[int]:
    """Apply pending migrations. Returns the versions applied in this call."""
    db.script(
        [
            'CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY, name TEXT NOT NULL, applied_at TEXT NOT NULL)'
        ]
    )
    if db.dialect == POSTGRES:
        db.execute('SELECT pg_advisory_xact_lock(?)', (_LOCK_ID,))
    else:
        db.commit()

    applied = {r['version'] for r in db.all('SELECT version FROM schema_migrations')}
    newly_applied: list[int] = []
    try:
        for version, name, step in MIGRATIONS:
            if version in applied:
                continue
            step(db)
            db.execute(
                "INSERT INTO schema_migrations (version, name, applied_at) VALUES (?, ?, CURRENT_TIMESTAMP)",
                (version, name),
            )
            if db.dialect != POSTGRES:
                db.commit()
            newly_applied.append(version)
            log.info('Applied migration %s: %s', version, name)
        db.commit()
    except Exception:
        db.rollback()
        raise
    return newly_applied


def current_version(db: Database) -> int:
    try:
        return int(db.scalar('SELECT MAX(version) AS v FROM schema_migrations', default=0))
    except Exception:
        db.rollback()
        return 0
