/* Dashboard: natural-language quick add and asynchronously loaded insights. */
(function () {
  'use strict';
  const { api, formatINR, niceDate } = window.Ledgerly;

  function el(tag, attrs = {}, ...children) {
    const node = document.createElement(tag);
    Object.entries(attrs).forEach(([k, v]) => {
      if (k === 'class') node.className = v; else node.setAttribute(k, v);
    });
    children.flat().forEach((c) => node.append(c instanceof Node ? c : document.createTextNode(String(c))));
    return node;
  }

  // ---- Quick add --------------------------------------------------------------
  const form = document.getElementById('nl-form');
  if (form) {
    const input = document.getElementById('nl-input');
    const submit = document.getElementById('nl-submit');
    const status = document.getElementById('nl-status');
    const preview = document.getElementById('nl-preview');
    const editLink = document.getElementById('nl-edit');
    const editBase = editLink.getAttribute('href');
    let draft = null;

    const setStatus = (text, isError = false) => {
      status.textContent = text;
      status.classList.toggle('is-error', isError);
    };
    const reset = () => { draft = null; preview.classList.add('hidden'); };

    form.addEventListener('submit', async (e) => {
      e.preventDefault();
      const text = input.value.trim();
      if (!text) { setStatus('Describe the transaction first.', true); input.focus(); return; }
      submit.disabled = true;
      submit.innerHTML = '<i class="fa-solid fa-circle-notch spin" aria-hidden="true"></i> Reading…';
      setStatus('');
      reset();
      try {
        const result = await api(form.dataset.endpoint, { method: 'POST', body: { text } });
        draft = result.transaction;
        document.getElementById('pv-amount').textContent = formatINR(draft.amount);
        document.getElementById('pv-type').textContent = draft.type === 'income' ? 'Income' : 'Expense';
        document.getElementById('pv-category').textContent = draft.title && draft.title !== draft.category ? `${draft.category} · ${draft.title}` : draft.category;
        document.getElementById('pv-date').textContent = niceDate(draft.date);
        const params = new URLSearchParams({
          type: draft.type, amount: draft.amount, category: draft.category, date: draft.date,
          title: draft.title || '', description: draft.description || '', next: window.location.pathname,
        });
        editLink.href = `${editBase}?${params}`;
        preview.classList.remove('hidden');
        setStatus(result.source === 'gemini' ? 'Understood with Gemini. Check the details, then save.' : 'Parsed with built-in rules. Check the details, then save.');
        document.getElementById('nl-save').focus();
      } catch (err) {
        setStatus(err.message, true);
      } finally {
        submit.disabled = false;
        submit.textContent = 'Preview';
      }
    });

    document.getElementById('nl-save').addEventListener('click', async (e) => {
      if (!draft) return;
      e.target.disabled = true;
      try {
        await api(form.dataset.save, { method: 'POST', body: draft });
        setStatus(`Saved ${formatINR(draft.amount)} to ${draft.category}. Refreshing…`);
        window.location.reload();
      } catch (err) {
        setStatus(err.message, true);
        e.target.disabled = false;
      }
    });
    document.getElementById('nl-cancel').addEventListener('click', () => { reset(); setStatus('Discarded.'); input.focus(); });
  }

  // ---- Insights -------------------------------------------------------------------
  const card = document.getElementById('insights');
  if (card) {
    const body = document.getElementById('insights-body');
    const icons = ['fa-chart-line', 'fa-bullseye', 'fa-arrow-right-arrow-left'];
    const tones = ['tone-teal', 'tone-amber', 'tone-indigo'];
    api(card.dataset.endpoint)
      .then(({ insights }) => {
        body.replaceChildren();
        if (insights.summary) body.append(el('p', { class: 'text-2', style: 'margin-bottom: 14px; font-weight: 600' }, insights.summary));
        const list = el('ul', { class: 'insights' });
        (insights.insights || []).forEach((text, i) => {
          list.append(el('li', {}, el('span', { class: `dot ${tones[i % 3]}`, 'aria-hidden': 'true' }, el('i', { class: `fa-solid ${icons[i % 3]}` })), el('span', {}, text)));
        });
        body.append(list);
        if (insights.tip) body.append(el('div', { class: 'tip' }, el('i', { class: 'fa-solid fa-lightbulb', 'aria-hidden': 'true' }), el('span', {}, el('strong', {}, 'Tip: '), insights.tip)));
        const source = insights.source === 'gemini' ? 'Written by Gemini from your monthly totals' : 'Generated by built-in rules';
        body.append(el('p', { class: 'source-note' }, el('i', { class: 'fa-solid fa-circle-info', 'aria-hidden': 'true' }), insights.note || source));
      })
      .catch(() => {
        body.replaceChildren(el('p', { class: 'muted' }, 'Insights are unavailable right now. Your data is safe; try refreshing in a moment.'));
      })
      .finally(() => body.setAttribute('aria-busy', 'false'));
  }
})();
